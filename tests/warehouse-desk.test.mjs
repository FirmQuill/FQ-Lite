import test from 'node:test';
import assert from 'node:assert/strict';
import {apply,newVault,validateState,position} from '../core.mjs';
import {deskOf} from '../desk-core.mjs';
import {warehouseView,liteWarehouseUnits,warehouseLabel} from '../warehouse-desk.mjs';
test('offline owner warehouse metadata stays in the book, follows movement and never double posts stock',()=>{
 let state=newVault('Fictional Stock Room',['stock']);const id=state.companies[0].id,book=()=>state.companies[0];
 const act=p=>state=apply(state,id,{date:'2026-11-20',...p});
 assert.equal(book().desk,undefined);
 act({type:'item',kind:'Product',name:'Bracket & sleeve <literal>'});const {id:item}=book().items[0];
 act({type:'adjust in',item,qty:10,amount:2500,location:'Main'});
 act({type:'tracked unit',unitId:'PAL-010',kind:'Pallet',name:'<Warehouse pallet>',location:'Main',contents:[{item,qty:8}]});const {id:unitId}=deskOf(book()).units[0];
 const before={moves:structuredClone(book().moves),journal:structuredClone(book().entries)};
 act({type:'warehouse-bin',unitId,bin:'A&4'});
 act({type:'warehouse-trace',unitId,itemId:item,serial:'serial-1',lot:'lot-01',expiry:'2026-11-21',quantity:1});
 assert.throws(()=>act({type:'warehouse-trace',unitId,itemId:item,serial:'SERIAL-1',quantity:1}),/already assigned/);
 assert.throws(()=>act({type:'warehouse-trace',unitId,itemId:item,lot:'lot-02',quantity:8}),/exceed/);
 act({type:'warehouse-reorder',itemId:item,location:'Main',minimum:10,target:20});
 const w=()=>warehouseView(deskOf(book()).warehouse,book(),liteWarehouseUnits(deskOf(book()).units),'2026-11-21');
 assert.equal(w().traces[0].expired,true);assert.equal(w().traces[0].currentBin,'A&4');assert.equal(w().reorder[0].suggested,10);
 assert.deepEqual(book().moves,before.moves);assert.deepEqual(book().entries,before.journal);
 const label=warehouseLabel(deskOf(book()).units[0],w().bins[0].bin);assert.match(label,/PAL-010/);assert.match(label,/&lt;Warehouse pallet&gt;/);assert.match(label,/A&amp;4/);assert.doesNotMatch(label,/<Warehouse pallet>/);
 act({type:'unit movement',unit:unitId,location:'Dock'});assert.equal(w().traces[0].currentLocation,'Dock');assert.equal(w().bins[0].bin,'');assert.equal(w().reorder[0].suggested,18);
 act({type:'unit movement',unit:unitId,location:'Main'});assert.equal(w().bins[0].bin,'');
 const traceId=w().traces[0].id;
 assert.throws(()=>act({type:'warehouse-trace-release',traceId,date:'2026-11-19',note:'Earlier'}),/precedes/);
 act({type:'warehouse-trace-release',traceId,note:'Verified outgoing stock'});assert.equal(w().traces[0].releaseNote,'Verified outgoing stock');
 act({type:'warehouse-reorder',itemId:item,location:'Main',minimum:0,target:0});
 assert.equal(w().reorder.length,0);assert.deepEqual(position(book(),item,'Main'),{qty:10,value:2500});
 validateState(JSON.parse(JSON.stringify(state)));
});
